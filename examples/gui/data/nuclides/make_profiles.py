#!/usr/bin/env python3
"""Builds the gamma source profiles used by the GUI ("Gamma source" photons).

Each profile lists the photons emitted per decay: one row per line with the
energy in keV and the emission intensity in % per decay. The detector
response is computed separately for each scintillator material and size by
tools/make_spectra.cpp (run at build time).

Decay data (gamma, annihilation and K X-ray lines) are downloaded from the
LNHB / DDEP "Nucleide-Lara" library: https://www.lnhb.fr/nuclides/

Usage: python3 make_profiles.py   (writes <Nuclide>.csv next to this script)
"""

import datetime
import os
import urllib.request

NUCLIDES = ["Am-241", "Co-57", "Ba-133", "Na-22", "Cs-137", "Mn-54", "Zn-65",
            "Bi-207", "Co-60", "Y-88", "K-40", "Eu-152"]
URL = "https://www.lnhb.fr/nuclides/{}.lara.txt"

MIN_ENERGY_KEV = 20.0    # softer X-rays are absorbed before reaching a crystal
MIN_INTENSITY_PCT = 0.1  # ignore weaker lines


def fetch_lines(nuclide):
    """Returns [(energy keV, intensity %, type)] of gammas, annihilation and K X-rays."""
    with urllib.request.urlopen(URL.format(nuclide), timeout=60) as r:
        text = r.read().decode("utf-8", "replace")
    lines = []
    for row in text.splitlines():
        cols = [c.strip() for c in row.split(";")]
        if len(cols) < 5:
            continue
        try:
            energy, intensity = float(cols[0]), float(cols[2])
        except ValueError:
            continue
        kind = cols[4]
        if not (kind == "g" or kind == "g511" or kind.startswith("XK")):
            continue
        if energy >= MIN_ENERGY_KEV and intensity >= MIN_INTENSITY_PCT:
            lines.append((energy, intensity, kind))
    return lines


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    today = datetime.date.today().isoformat()
    for nuclide in NUCLIDES:
        lines = fetch_lines(nuclide)
        with open(os.path.join(here, f"{nuclide}.csv"), "w") as f:
            f.write(f"# {nuclide} photon emissions per decay (E >= {MIN_ENERGY_KEV:g} keV, I >= {MIN_INTENSITY_PCT:g}%)\n")
            f.write(f"# Decay data: LNHB/DDEP Nucleide-Lara {URL.format(nuclide)} (retrieved {today})\n")
            f.write("# Generated by make_profiles.py\n")
            f.write("# energy_keV,intensity_pct,type\n")
            for energy, intensity, kind in lines:
                f.write(f"{energy:g},{intensity:g},{kind}\n")
        print(f"{nuclide}: {len(lines)} lines")


if __name__ == "__main__":
    main()
