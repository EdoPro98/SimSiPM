/** @class sipm::SiPMHit SiPMHit.h
 *
 * @brief Class storing information relative to a single SiPM hit cell.
 *
 * This class is used mainly to store information relative to a single hit on a
 * SiPM cell. Information stored in this class will be used to generate the
 * signal for each SiPM cell.
 *
 *  @author Edoardo Proserpio
 *  @date 2020
 */

#ifndef SIPM_SIPMHITS_H
#define SIPM_SIPMHITS_H

#include <cstdint>
#include <iomanip>
#include <iostream>
#include <sstream>

namespace sipm {
class SiPMHit {
public:
  /** @enum HitType
   * Defines the generating process for the hit
   */
  enum class HitType : uint8_t {
    kPhotoelectron,           ///< Hit generated by a photoelectron
    kDarkCount,               ///< Hit generated by a dark count event
    kOpticalCrosstalk,        ///< Hit generated by an optical crosstalk
    kDelayedOpticalCrosstalk, ///< Hit generated by a delayed optical crosstalk
    kFastAfterPulse,          ///< Hit generated by a fast afterpulse
    kSlowAfterPulse           ///< Hit generated by a slow afterpulse
  };

  /// @brief Creates a hit
  /// @param time Time of the hit in ns
  /// @param amp Relative amplitude of the pulse (1 = one photoelectron)
  /// @param row Row of the hit cell
  /// @param col Column of the hit cell
  /// @param type Process that generated the hit
  /// @param parentIdx Index of the parent hit in the sensor hit list, -1 if none
  constexpr SiPMHit(double time, float amp, uint32_t row, uint32_t col, HitType type,
                    int32_t parentIdx = -1) noexcept
    : m_Time(time), m_Amplitude(amp), m_Row(row), m_Col(col), m_HitType(type), m_ParentIdx(parentIdx) {}


  /// @brief Comparison operator for hits
  /**
   * Hits are ordered based on their time:
   * @f[Hit_1 < Hit_2 \Leftrightarrow Hit_1.time < Hit_2.time @f]
   * Sorting a vector of hits gives the chronological order of hits by
   * arriving/generating time.
   * @param rhs Hit to compare with
   * @return true if this hit is earlier than @p rhs
   */
  constexpr bool operator<(const SiPMHit& rhs) const noexcept { return m_Time < rhs.m_Time; }
  /// @brief Chronological order, see operator<
  /// @param rhs Hit to compare with
  /// @return true if this hit is not later than @p rhs
  constexpr bool operator<=(const SiPMHit& rhs) const noexcept { return !(rhs < *this); }
  /// @brief Chronological order, see operator<
  /// @param rhs Hit to compare with
  /// @return true if this hit is later than @p rhs
  constexpr bool operator>(const SiPMHit& rhs) const noexcept { return rhs < *this; }
  /// @brief Chronological order, see operator<
  /// @param rhs Hit to compare with
  /// @return true if this hit is not earlier than @p rhs
  constexpr bool operator>=(const SiPMHit& rhs) const noexcept { return !(*this < rhs); }

  /// @brief Operator used to check if the hit is generated in the same cell
  /**
   * Hits are considered equal if they have same row and column,
   * hence the same SiPM cell
   * @param rhs Hit to compare with
   * @return true if both hits are in the same cell
   */
  constexpr bool operator==(const SiPMHit& rhs) const noexcept { return m_Row == rhs.m_Row && m_Col == rhs.m_Col; }

  /// @brief Time of the hit
  /// @return Hit time in ns
  constexpr double time() const noexcept { return m_Time; }
  /// @brief Row of the hit cell
  /// @return Row index
  constexpr uint32_t row() const noexcept { return m_Row; }
  /// @brief Column of the hit cell
  /// @return Column index
  constexpr uint32_t col() const noexcept { return m_Col; }
  /// @brief Amplitude of the pulse produced by the hit
  /// @return Relative amplitude (1 = one photoelectron); includes cell-to-cell gain variation and cell recovery
  float amplitude() const noexcept { return m_Amplitude; }
  /// @brief Modifiable amplitude of the hit
  /// @return Reference to the amplitude
  float& amplitude() { return m_Amplitude; }
  /// @brief Process that generated the hit
  /// @return The @ref HitType
  constexpr HitType hitType() const noexcept { return m_HitType; }
  /// @brief Parent of the hit
  /// @return Index of the parent hit in the sensor hit list (SiPMSensor::hits()), -1 if none
  constexpr int32_t parentIdx() const noexcept { return m_ParentIdx; }
  /// @brief Modifiable parent index of the hit
  /// @return Reference to the parent index
  int32_t& parentIdx() { return m_ParentIdx; }

  /// @brief Prints time, amplitude, position and type of the hit
  friend std::ostream& operator<<(std::ostream&, const SiPMHit&);
  /// @brief Description of the hit
  /// @return String printed by operator<<
  std::string toString() const {
    std::stringstream ss;
    ss << *this;
    return ss.str();
  }

  // Always construct hits with values and no default constructor
  SiPMHit() = delete;

private:
  double m_Time;  ///< Time of the hit in ns
  int32_t m_ParentIdx;  ///< Index into the sensor hit list, -1 = no parent
  float m_Amplitude;  ///< Relative amplitude (1 = one photoelectron)
  uint32_t m_Row;  ///< Row of the hit cell
  uint32_t m_Col;  ///< Column of the hit cell
  HitType m_HitType;  ///< Process that generated the hit
};

inline std::ostream& operator<<(std::ostream& out, const SiPMHit& obj) {
  out << std::setprecision(2) << std::fixed;
  out << "===> SiPM Hit <===\n";
  out << "Address: " << std::hex << std::addressof(obj) << "\n";
  out << "Hit time: " << std::dec << obj.m_Time << "\n";
  out << "Hit relative amplitude: " << obj.m_Amplitude << "\n";
  out << "Hit position on sensor: " << obj.m_Row << " - " << obj.m_Col << "\n";
  out << "Hit type: ";
  switch (obj.m_HitType) {
    case SiPMHit::HitType::kPhotoelectron:
      out << "Photoelectron\n";
      break;
    case SiPMHit::HitType::kDarkCount:
      out << "Dark count\n";
      break;
    case SiPMHit::HitType::kOpticalCrosstalk:
      out << "Optical crosstalk\n";
      break;
    case SiPMHit::HitType::kFastAfterPulse:
      out << "Afterpulse (fast)\n";
      break;
    case SiPMHit::HitType::kSlowAfterPulse:
      out << "Afterpulse (slow)\n";
      break;
    case SiPMHit::HitType::kDelayedOpticalCrosstalk:
      out << "Delayed optical crosstalk\n";
      break;
  }
  return out;
}
} // namespace sipm
#endif /* SIPM_SIPMHITS_H */
